import { execSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

/**
 * Generates src/data/changelog.ts from git history so every feature push
 * automatically appears on the app's Changelog page, pinned to the same
 * version number shown in Settings (0.1.<commit-count>).
 */
function run(cmd) {
  return execSync(cmd, { encoding: 'utf8' }).trim()
}

const total = Number(run('git rev-list --count HEAD'))
if (!Number.isFinite(total)) {
  console.warn('git unavailable — skipping changelog generation')
  process.exit(0)
}

// %H sha, %s subject, %aI author date; log newest-first, so +i gives the 1-based commit ordinal.
const lines = run('git log --format="%H %s %aI"').split('\n').filter(Boolean)

const entries = []
for (let i = 0; i < lines.length; i++) {
  const [sha, ...rest] = lines[i].split(' ')
  const subject = rest.slice(0, -1).join(' ')
  const date = rest[rest.length - 1]
  const isFeature = /^feat(\([^)]+\))?:/.test(subject) || /^fix(\([^)]+\))?:/.test(subject)
  if (!isFeature) continue
  entries.push({
    version: `0.1.${total - i}`,
    date: date.slice(0, 10),
    title: subject.replace(/^feat(\([^)]+\))?:\s*|^fix(\([^)]+\))?:\s*/i, ''),
    sha,
  })
}

const out = resolve(process.cwd(), 'src/data/changelog.ts')
const body = `// Auto-generated by scripts/gen-changelog.mjs — do not edit by hand.\nexport interface ChangelogEntry {\n  version: string\n  date: string\n  title: string\n  sha: string\n}\n\nexport const CHANGELOG: ChangelogEntry[] = ${JSON.stringify(entries, null, 2)}\n`
writeFileSync(out, body)
console.log(`changelog: ${entries.length} entries written`)